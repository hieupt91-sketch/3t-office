import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { launchApp } from "./session.mjs";
import { mouseClick, press, sleep, typeText } from "./actions.mjs";

const localAppData = process.env.VNO_CDP_LOCALAPPDATA;
if (!localAppData) throw new Error("Set VNO_CDP_LOCALAPPDATA to a unique profile path before running.");
const outputDir = path.resolve("docs/assets/q50-ui");
mkdirSync(outputDir, { recursive: true });
const session = await launchApp("slides", { localAppData });
let failed = false;
try {
  const win = await session.cdp.send("Browser.getWindowForTarget", {});
  await session.cdp.send("Browser.setWindowBounds", { windowId: (win.result || win).windowId, bounds: { windowState: "normal", width: 1366, height: 768 } });
  const started = await session.cdp.evaluate(`(() => { const canvas=window.__vnoAppInstance?.adapter?.canvas; if(!canvas) return false; const base=structuredClone(canvas.slides[0]); for(let i=1;i<3;i++) canvas.slides.push({...structuredClone(base),id:'q50-show-'+i,title:'Trang thử '+(i+1),body:'Nội dung thử '+(i+1)}); return Boolean(window.__show=canvas.startSlideShow(0)); })()`);
  if (!started) throw new Error("Could not start slide show through the app canvas.");
  await sleep(300);
  for (const theme of ["light", "dark"]) {
    await session.cdp.evaluate(`document.documentElement.dataset.theme=${JSON.stringify(theme)}`);
    const idle = await session.cdp.evaluate(`(() => ({hint:document.querySelector('.vno-slideshow-content')?.innerText?.includes('Esc'), controls:document.querySelector('.vno-slideshow-controls')?.getAttribute('data-visible')||null, slideRect:document.querySelector('.vno-slideshow-content')?.getBoundingClientRect().toJSON()}))()`);
    const shot = await session.cdp.send("Page.captureScreenshot", { format: "png", captureBeyondViewport: false });
    writeFileSync(path.join(outputDir, `slides-show-idle-${theme}-after-1366x768.png`), Buffer.from((shot.result || shot).data, "base64"));
    console.log(`${idle.hint && idle.controls !== "true" ? "PASS" : "FAIL"} | show idle ${theme} | ${JSON.stringify(idle)}`);
    if (!idle.hint || idle.controls === "true") failed = true;
    await session.cdp.send("Input.dispatchMouseEvent", { type: "mouseMoved", x: 680, y: 680 });
    await sleep(150);
    const visible = await session.cdp.evaluate(`(() => { const e=document.querySelector('.vno-slideshow-controls'); const r=e?.getBoundingClientRect(); const f=document.querySelector('.vno-slide-master-footer')?.getBoundingClientRect(); return {controls:!!e, visible:e?.classList.contains('is-visible')||e?.dataset.visible==='true', rect:r&&r.toJSON(), footerRect:f&&f.toJSON(), overlapsFooter:!!r&&!!f&&r.left<f.right&&r.right>f.left&&r.top<f.bottom&&r.bottom>f.top, text:e?.innerText?.trim()}; })()`);
    const hoverShot = await session.cdp.send("Page.captureScreenshot", { format: "png", captureBeyondViewport: false });
    writeFileSync(path.join(outputDir, `slides-show-controls-${theme}-after-1366x768.png`), Buffer.from((hoverShot.result || hoverShot).data, "base64"));
    const toolbar = await session.cdp.evaluate(`(() => { const e=document.querySelector('.vno-slideshow-controls'); const r=e?.getBoundingClientRect(); return {counter:e?.querySelector('.vno-slideshow-control-counter')?.textContent, buttons:[...e.querySelectorAll('button')].map(b=>b.dataset.showControl), inBounds:!!r&&r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight}; })()`);
    if (!toolbar.buttons?.includes("previous") || !toolbar.buttons?.includes("next") || !toolbar.buttons?.includes("pen") || !toolbar.buttons?.includes("laser") || !toolbar.buttons?.includes("exit") || !toolbar.inBounds) failed = true;
    console.log(`${toolbar.inBounds ? "PASS" : "FAIL"} | show control buttons and page count ${theme} | ${JSON.stringify(toolbar)}`);
    const next = await session.cdp.evaluate(`(() => { const r=document.querySelector('[data-show-control="next"]').getBoundingClientRect(); return {x:r.x+r.width/2,y:r.y+r.height/2}; })()`);
    await mouseClick(session.cdp, next.x, next.y);
    if (await session.cdp.evaluate("window.__show.getIndex()") !== 1) failed = true;
    const previous = await session.cdp.evaluate(`(() => { const r=document.querySelector('[data-show-control="previous"]').getBoundingClientRect(); return {x:r.x+r.width/2,y:r.y+r.height/2}; })()`);
    await mouseClick(session.cdp, previous.x, previous.y);
    if (await session.cdp.evaluate("window.__show.getIndex()") !== 0) failed = true;
    await session.cdp.send("Input.dispatchMouseEvent", { type: "mouseMoved", x: 100, y: 100 });
    console.log(`${visible.visible && !visible.overlapsFooter ? "PASS" : "FAIL"} | show controls on pointer move ${theme} | ${JSON.stringify(visible)}`);
    if (!visible.visible || visible.overlapsFooter) failed = true;
    await sleep(2200);
    const hidden = await session.cdp.evaluate(`(() => { const e=document.querySelector('.vno-slideshow-controls'); return {exists:!!e, visible:e?.classList.contains('is-visible')||e?.dataset.visible==='true'}; })()`);
    console.log(`${!hidden.visible ? "PASS" : "FAIL"} | controls hide after idle ${theme} | ${JSON.stringify(hidden)}`);
    if (hidden.visible) failed = true;
  }
  await press(session.cdp, "ArrowRight");
  if (await session.cdp.evaluate("window.__show.getIndex()") !== 1) failed = true;
  await press(session.cdp, "ArrowDown");
  if (await session.cdp.evaluate("window.__show.getIndex()") !== 2) failed = true;
  await press(session.cdp, "ArrowUp");
  if (await session.cdp.evaluate("window.__show.getIndex()") !== 1) failed = true;
  await press(session.cdp, "PageDown");
  if (await session.cdp.evaluate("window.__show.getIndex()") !== 2) failed = true;
  await press(session.cdp, "PageUp");
  if (await session.cdp.evaluate("window.__show.getIndex()") !== 1) failed = true;
  await press(session.cdp, "Home");
  if (await session.cdp.evaluate("window.__show.getIndex()") !== 0) failed = true;
  await press(session.cdp, "End");
  if (await session.cdp.evaluate("window.__show.getIndex()") !== 2) failed = true;
  await typeText(session.cdp, "2", 0);
  await press(session.cdp, "Enter");
  const numbered = await session.cdp.evaluate("window.__show.getIndex()");
  console.log(`${numbered === 1 ? "PASS" : "FAIL"} | number + Enter opens requested slide | index=${numbered}`);
  if (numbered !== 1) failed = true;
  await press(session.cdp, "ArrowLeft");
  const clickAt = { x: 500, y: 600 };
  await mouseClick(session.cdp, clickAt.x, clickAt.y);
  const clickIndex = await session.cdp.evaluate("window.__show.getIndex()");
  console.log(`${clickIndex === 1 ? "PASS" : "FAIL"} | click advances one slide | index=${clickIndex}`);
  if (clickIndex !== 1) failed = true;
  await press(session.cdp, "Home");
  await press(session.cdp, "Enter");
  const enterIndex = await session.cdp.evaluate("window.__show.getIndex()");
  console.log(`${enterIndex === 1 ? "PASS" : "FAIL"} | Enter advances one slide | index=${enterIndex}`);
  if (enterIndex !== 1) failed = true;
  await press(session.cdp, "Home");
  await press(session.cdp, " ");
  const spaceIndex = await session.cdp.evaluate("window.__show.getIndex()");
  console.log(`${spaceIndex === 1 ? "PASS" : "FAIL"} | Space advances one slide | index=${spaceIndex}`);
  if (spaceIndex !== 1) failed = true;
  await press(session.cdp, "Escape");
} finally {
  await session.close();
}
if (failed) process.exitCode = 1;
