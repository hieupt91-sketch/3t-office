"""MAC-9 — font configuration for the headless document engine (LibreOffice).

On macOS the engine runs headless and resolves fonts through its bundled fontconfig, which by default has no
configuration file: it sees only the fonts shipped inside the engine. This module writes the fontconfig file
LibreOffice reads (selected through the FONTCONFIG_FILE environment variable of the engine processes):
  * <dir> entries for the OS font folders the OS backend lists (fonts used in place, never copied),
  * a <cachedir> so the font scan is done once, not at every conversion,
  * <alias> rules "font -> substitutes" in the same form LibreOffice's own fc_local.conf uses for
    Calibri -> Carlito. The requested font stays first, so an installed real font always wins.
Nothing OS-specific lives here: the folders and the table come from platform/os_services/<os>.py.
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path
from typing import Iterable, NamedTuple
from xml.sax.saxutils import escape

FONTCONFIG_FILE_NAME = "fonts.conf"
CACHE_DIR_NAME = "cache"
ENV_VAR = "FONTCONFIG_FILE"


class FontConfigResult(NamedTuple):
    # NamedTuple, not a dataclass: main.py loads this file by path without registering it in sys.modules.
    ok: bool
    path: Path | None = None
    changed: bool = False
    reason: str = ""


def _text(value: object) -> str:
    return escape(str(value), {'"': "&quot;"})


def fontconfig_document(directories: Iterable[Path | str], substitutions: Iterable[object], cache_dir: Path | str,
                        accept_globs: Iterable[str] = (), reject_globs: Iterable[str] = ()) -> str:
    """Build the fontconfig XML. substitutions: objects with .font and .substitutes (tuple of names)."""
    lines = [
        '<?xml version="1.0"?>',
        '<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">',
        "<!-- Generated by 3T Office at start-up (MAC-9). Local edits are overwritten. -->",
        "<fontconfig>",
    ]
    for directory in directories:
        lines.append(f"  <dir>{_text(directory)}</dir>")
    lines.append(f"  <cachedir>{_text(cache_dir)}</cachedir>")
    accept, reject = list(accept_globs), list(reject_globs)
    if accept or reject:
        lines.append("  <selectfont>")
        if accept:
            lines.append("    <acceptfont>" + "".join(f"<glob>{_text(g)}</glob>" for g in accept) + "</acceptfont>")
        if reject:
            lines.append("    <rejectfont>" + "".join(f"<glob>{_text(g)}</glob>" for g in reject) + "</rejectfont>")
        lines.append("  </selectfont>")
    seen = set()
    for item in substitutions:
        font = str(getattr(item, "font", "") or "").strip()
        subs = [str(s).strip() for s in getattr(item, "substitutes", ()) if str(s).strip()]
        key = font.casefold()
        if not font or not subs or key in seen:
            continue
        seen.add(key)
        accepted = "".join(f"<family>{_text(s)}</family>" for s in subs)
        lines.append(f'  <alias binding="same"><family>{_text(font)}</family><accept>{accepted}</accept></alias>')
    lines.append("</fontconfig>")
    return "\n".join(lines) + "\n"


def write_engine_font_config(target_dir: Path, document_fonts: object) -> FontConfigResult:
    """Write <target_dir>/fonts.conf from an OS DocumentFonts service; rewrite only when the content changes.

    Never raises for I/O problems: the engine then keeps its previous behaviour (bundled fonts only).
    """
    if document_fonts is None:
        return FontConfigResult(False, reason="no document font service for this OS")
    target = Path(target_dir)
    try:
        sources = document_fonts.sources()
        content = fontconfig_document(sources.directories, document_fonts.substitutions(), target / CACHE_DIR_NAME,
                                      sources.accept_globs, sources.reject_globs)
        (target / CACHE_DIR_NAME).mkdir(parents=True, exist_ok=True)
        path = target / FONTCONFIG_FILE_NAME
        try:
            if path.read_text(encoding="utf-8") == content:
                return FontConfigResult(True, path, changed=False)
        except (OSError, UnicodeDecodeError):
            pass
        fd, temp = tempfile.mkstemp(prefix=".fonts-", suffix=".conf", dir=target)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                handle.write(content)
            os.replace(temp, path)
        except BaseException:
            Path(temp).unlink(missing_ok=True)
            raise
        return FontConfigResult(True, path, changed=True)
    except OSError as exc:
        return FontConfigResult(False, reason=f"{type(exc).__name__}: {exc}"[:200])


def engine_environment(result: FontConfigResult) -> dict[str, str]:
    """Environment the engine processes need for the written configuration (empty when nothing was written)."""
    return {ENV_VAR: str(result.path)} if result.ok and result.path is not None else {}
