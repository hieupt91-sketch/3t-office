import fs from "node:fs/promises";
import path from "node:path";
import { launchApp } from "../../../tests/live/cdp/session.mjs";
import { click, press, typeText } from "../../../tests/live/cdp/actions.mjs";

const dir = process.env.VNO_CDP_LOCALAPPDATA;
const root = process.env.VNO_APP_ROOT || process.cwd();
if (!dir) throw new Error("VNO_CDP_LOCALAPPDATA is required.");
const input = path.join(dir, "template.docx");
const session = await launchApp("writer", { root, filePath: input, localAppData: path.join(dir, "group6_profiles", "writer"), startTimeoutMilliseconds: 180000, readyTimeoutMilliseconds: 180000 });
const cdp = session.cdp;
const command = id => click(cdp, `button[data-command-id="${id}"]`);
try {
  await cdp.waitFor("!!document.querySelector('.vno-writer-body')", { timeoutMilliseconds: 180000 });
  await click(cdp, ".vno-writer-body");
  await typeText(cdp, "alpha beta", 10);
  await press(cdp, "Enter");
  await typeText(cdp, "gamma delta", 10);
  const review = await cdp.evaluate("[...document.querySelectorAll('.vno-ribbon-tab')].findIndex(x=>/Đánh giá|Review/i.test(x.textContent))");
  await click(cdp, ".vno-ribbon-tab", review);
  const spellBefore = await cdp.evaluate("window.__vnoAppInstance.spellcheckController?.enabled");
  await command("writer.review.toggleSpellCheck");
  const spellChanged = await cdp.evaluate("({before:window.__vnoAppInstance.spellcheckController?.enabled,checked:document.querySelector('button[data-command-id=\"writer.review.toggleSpellCheck\"]')?.classList.contains('is-checked')})");
  await command("writer.review.toggleSpellCheck");
  await command("writer.review.wordCount");
  await cdp.waitFor("!!document.querySelector('#vno-wordcount-overlay')", { timeoutMilliseconds: 10000 });
  const count = await cdp.evaluate(`Object.fromEntries([...document.querySelectorAll('#vno-wordcount-overlay [data-stat]')].map(x=>[x.dataset.stat,Number(x.textContent.replace(/\\./g,''))]))`);
  const countScreenshot = await cdp.send("Page.captureScreenshot", { format: "png", captureBeyondViewport: false });
  await fs.writeFile(path.join(dir, "t11_group6_wordcount.png"), Buffer.from(countScreenshot.result.data, "base64"));
  await click(cdp, "#vno-wordcount-overlay .vno-dialog-ok-btn");
  const view = await cdp.evaluate("[...document.querySelectorAll('.vno-ribbon-tab')].findIndex(x=>/Xem|View/i.test(x.textContent))");
  await click(cdp, ".vno-ribbon-tab", view);
  await command("writer.view.readMode");
  const readMode = await cdp.evaluate("({active:document.querySelector('.vno-writer-read-mode')!=null,toolbar:document.querySelector('.vno-writer-read-toolbar')?.getAttribute('role')})");
  await press(cdp, "Escape");
  await command("writer.view.webLayout");
  const webLayout = await cdp.evaluate("document.querySelector('.vno-writer-container')?.classList.contains('vno-writer-web-layout')");
  await command("writer.view.printLayout");
  await command("writer.view.navigationPane");
  const navigation = await cdp.evaluate("({open:document.querySelector('.vno-writer-navigation-pane')?.getAttribute('aria-label'),element:document.querySelector('.vno-writer-navigation-pane')?.className})");
  await command("writer.view.navigationPane");
  await command("writer.view.ruler");
  const rulerHidden = await cdp.evaluate("document.querySelector('.vno-writer-ruler')?.hidden ?? null");
  const verticalRulerHidden = await cdp.evaluate("document.querySelector('.vno-writer-ruler-vertical')?.hidden ?? null");
  await command("writer.view.ruler");
  await command("writer.view.gridlines");
  const gridlines = await cdp.evaluate("document.querySelector('.vno-writer-container')?.classList.contains('vno-writer-gridlines')");
  await command("writer.view.gridlines");
  await command("writer.view.zoomIn");
  const zoomIn = await cdp.evaluate("document.querySelector('.vno-writer-page')?.dataset.zoom");
  await command("writer.view.zoomOut");
  const zoomOut = await cdp.evaluate("document.querySelector('.vno-writer-page')?.dataset.zoom");
  await command("writer.view.zoom100");
  const zoom100 = await cdp.evaluate("document.querySelector('.vno-writer-page')?.dataset.zoom");
  await command("common.macro.recordToggle");
  await command("writer.view.zoomIn");
  await command("common.macro.recordToggle");
  await cdp.waitFor("!!document.querySelector('.vno-dialog-input')", { timeoutMilliseconds: 10000 });
  await cdp.evaluate(`document.querySelector('.vno-dialog-input').value='T11 Macro'`);
  await click(cdp, ".vno-dialog-ok-btn");
  await command("common.macro.manager");
  await cdp.waitFor("!!document.querySelector('.vno-macro-row')", { timeoutMilliseconds: 10000 });
  const macroName = await cdp.evaluate("document.querySelector('.vno-macro-name')?.textContent");
  const beforeRun = await cdp.evaluate("document.querySelector('.vno-writer-page')?.dataset.zoom");
  await click(cdp, ".vno-macro-row .vno-macro-run-btn");
  const afterRun = await cdp.evaluate("document.querySelector('.vno-writer-page')?.dataset.zoom");
  await click(cdp, ".vno-macro-close-btn");
  const docx = path.join(dir, "t11_group6_wordcount.docx");
  const saved = await cdp.evaluate(`globalThis.globalUnoBridge.saveRealFileInPlace("writer",window.__vnoAppInstance.adapter._contentForExport(),${JSON.stringify(docx)},${JSON.stringify(input)})`, { timeoutMilliseconds: 1200000 });
  if (saved?.status !== "ok") throw new Error(`Word count fixture save failed: ${JSON.stringify(saved)}`);
  const spellAfterRestore = await cdp.evaluate("window.__vnoAppInstance.spellcheckController?.enabled");
  const results = { spellBefore, spellChanged, spellAfterRestore, count, readMode, webLayout, navigation, rulerHidden, verticalRulerHidden, gridlines, zoomIn, zoomOut, zoom100, macroName, beforeRun, afterRun, docx };
  await fs.writeFile(path.join(dir, "t11_group6_app.json"), JSON.stringify(results, null, 2), "utf8");
  console.log(JSON.stringify(results));
} finally { await session.close(); }
