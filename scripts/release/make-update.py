#!/usr/bin/env python3
"""Build, sign, and publish a content-addressed VN Office patch using Python stdlib only."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from adapters.updater.crypto import (  # noqa: E402
    generate_rsa_key,
    private_key_from_pem,
    sign_sha256_pkcs1v15,
    write_private_key,
)
from adapters.updater.manifest import (  # noqa: E402
    MAX_PACKAGE_BYTES,
    compare_versions,
    validate_manifest,
    validate_package_path,
    version_key,
)


def _atomic_write(path: Path, content: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    with temp.open("wb") as stream:
        stream.write(content)
        stream.flush()
        os.fsync(stream.fileno())
    temp.replace(path)


def _sha256(path: Path) -> tuple[int, str]:
    digest = hashlib.sha256()
    size = 0
    with path.open("rb") as stream:
        while True:
            chunk = stream.read(1024 * 1024)
            if not chunk:
                break
            size += len(chunk)
            digest.update(chunk)
    return size, digest.hexdigest()


def _public_module(key: dict[str, int]) -> bytes:
    return (
        '"""Embedded update signing key. Generated by scripts/release/make-update.py --keygen."""\n\n'
        f'PUBLIC_KEY_N_HEX = "{key["n"]:0768x}"\n'
        f'PUBLIC_KEY_E = {key["e"]}\n\n'
        'def get_public_key() -> tuple[int, int] | None:\n'
        '    if len(PUBLIC_KEY_N_HEX) != 768:\n'
        '        return None\n'
        '    try:\n'
        '        modulus = int(PUBLIC_KEY_N_HEX, 16)\n'
        '    except ValueError:\n'
        '        return None\n'
        '    if modulus.bit_length() != 3072 or PUBLIC_KEY_E != 65537:\n'
        '        return None\n'
        '    return modulus, PUBLIC_KEY_E\n'
    ).encode("ascii")


def keygen(key_path: Path, public_module: Path, *, force: bool = False) -> tuple[Path, Path]:
    if key_path.exists() and not force:
        raise FileExistsError(f"Private key already exists; refusing to replace it: {key_path}")
    key = generate_rsa_key(3072)
    if key["n"].bit_length() != 3072:
        raise RuntimeError("Generated RSA key is not 3072 bits")
    public_module.parent.mkdir(parents=True, exist_ok=True)
    if force:
        write_private_key(key_path, key, overwrite=True)
    else:
        write_private_key(key_path, key)
    _atomic_write(public_module, _public_module(key))
    return key_path, public_module


def _load_key(path: Path) -> dict[str, int]:
    key = private_key_from_pem(path.read_bytes())
    if key["n"].bit_length() != 3072 or key["e"] != 65537:
        raise ValueError("Release key must be RSA 3072-bit with exponent 65537")
    return key


def _load_notes(args) -> str:
    if args.notes_file:
        notes = Path(args.notes_file).read_text(encoding="utf-8")
    else:
        notes = args.notes
    if not notes or not notes.strip():
        raise ValueError("Release notes in Vietnamese are required")
    return notes.strip()


def _inventory(package: Path, version: str, min_version: str, channel: str, notes: str) -> tuple[dict[str, object], bytes]:
    if not package.is_dir():
        raise FileNotFoundError(f"Package directory not found: {package}")
    version_file = package / "VERSION.txt"
    if not version_file.is_file() or version_file.read_text(encoding="ascii").strip() != version:
        raise ValueError("Package VERSION.txt must match --version exactly")
    main_py = package / "app" / "main.py"
    if main_py.is_file():
        source = main_py.read_text(encoding="utf-8")
        import re
        match = re.search(r'^APP_VERSION\s*=\s*[\'\"]([^\'\"]+)[\'\"]\s*$', source, re.MULTILINE)
        if not match or match.group(1) != version:
            raise ValueError("app/main.py APP_VERSION must match --version exactly")
    files = []
    total_size = 0
    for path in sorted(package.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"Package contains a symlink, which is not supported: {path}")
        if not path.is_file():
            continue
        relative = path.relative_to(package).as_posix()
        safe = validate_package_path(relative)
        size, digest = _sha256(path)
        total_size += size
        if total_size > MAX_PACKAGE_BYTES:
            raise ValueError("Package exceeds the 4 GiB inventory limit")
        files.append({"path": safe, "size": size, "sha256": digest})
    manifest = {
        "schema_version": 1,
        "version": version,
        "min_version": min_version,
        "channel": channel,
        "release_notes": notes,
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "files": files,
    }
    validate_manifest(manifest, expected_channel=channel)
    raw = (json.dumps(manifest, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8")
    return manifest, raw


def _copy_blob_once(source_file: Path, source_root: Path, digest: str) -> bool:
    blob = source_root / "files" / digest
    if blob.is_file():
        existing_size, existing_digest = _sha256(blob)
        source_size, source_digest = _sha256(source_file)
        if (existing_size, existing_digest) != (source_size, source_digest):
            raise ValueError(f"Existing content-addressed blob is corrupt: {blob}")
        return False
    blob.parent.mkdir(parents=True, exist_ok=True)
    temp = blob.with_name(f".{digest}.{os.getpid()}.tmp")
    shutil.copyfile(source_file, temp)
    if _sha256(temp) != _sha256(source_file):
        temp.unlink(missing_ok=True)
        raise OSError(f"Blob copy verification failed: {digest}")
    temp.replace(blob)
    return True


def publish(package: Path, source: Path, version: str, min_version: str, channel: str, notes: str, key_path: Path) -> dict[str, object]:
    version_key(version)
    version_key(min_version)
    if compare_versions(min_version, version) > 0:
        raise ValueError("--min-version cannot be newer than --version")
    key = _load_key(key_path)
    trust_path = package / "app" / "adapters" / "updater" / "trust.py"
    if not trust_path.is_file():
        raise ValueError("Built package is missing its embedded updater trust module")
    trust_text = trust_path.read_text(encoding="ascii")
    modulus_match = re.search(r'^PUBLIC_KEY_N_HEX\s*=\s*[\'\"]([0-9a-f]{768})[\'\"]\s*$', trust_text, re.MULTILINE)
    exponent_match = re.search(r"^PUBLIC_KEY_E\s*=\s*(\d+)\s*$", trust_text, re.MULTILINE)
    if not modulus_match or not exponent_match or int(modulus_match.group(1), 16) != key["n"] or int(exponent_match.group(1)) != key["e"]:
        raise ValueError("Signing key does not match the public key embedded in this package")
    manifest, raw = _inventory(package, version, min_version, channel, notes)
    version_dir = source / version
    manifest_path = version_dir / "manifest.json"
    signature_path = version_dir / "manifest.sig"
    if manifest_path.exists() and manifest_path.read_bytes() != raw:
        raise FileExistsError(f"This release version is already published with different contents: {version}")
    if signature_path.exists() and manifest_path.exists():
        existing_signature = signature_path.read_bytes()
        if existing_signature and existing_signature != sign_sha256_pkcs1v15(raw, key["n"], key["d"]):
            # PKCS#1 v1.5 is deterministic; this usually means the source was signed by another key.
            raise ValueError(f"Existing release signature does not match the configured key: {version}")
    uploaded = 0
    for item in manifest["files"]:
        package_file = package.joinpath(*str(item["path"]).split("/"))
        if _copy_blob_once(package_file, source, str(item["sha256"])):
            uploaded += int(item["size"])
    signature = sign_sha256_pkcs1v15(raw, key["n"], key["d"])
    _atomic_write(manifest_path, raw)
    _atomic_write(signature_path, signature)
    channel_pointer = {"channel": channel, "version": version}
    pointer_raw = (json.dumps(channel_pointer, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8")
    _atomic_write(source / "channels" / f"{channel}.json", pointer_raw)
    return {"version": version, "files": len(manifest["files"]), "new_blob_bytes": uploaded, "source": str(source)}


def _default_key_path() -> Path:
    user_profile = os.environ.get("USERPROFILE") or str(Path.home())
    return Path(user_profile) / ".vnoffice-release" / "signing-key.pem"


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--keygen", action="store_true", help="Generate the one-time RSA-3072 release key and embed its public key")
    parser.add_argument("--key-path", type=Path, default=_default_key_path(), help="Private key path outside the repository")
    parser.add_argument("--public-module", type=Path, default=REPO_ROOT / "adapters" / "updater" / "trust.py")
    parser.add_argument("--force", action="store_true", help="Explicitly replace an existing key during controlled key rotation")
    parser.add_argument("--package", type=Path, help="Built package directory from build-pilot.ps1")
    parser.add_argument("--source", type=str, help="Writable local or UNC update source directory")
    parser.add_argument("--version")
    parser.add_argument("--min-version", default="0.0.0")
    parser.add_argument("--channel", default="pilot")
    notes_group = parser.add_mutually_exclusive_group()
    notes_group.add_argument("--notes-file", type=Path, help="UTF-8 Vietnamese release notes file")
    notes_group.add_argument("--notes", help="Vietnamese release notes text")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    try:
        if args.keygen:
            key_path, public_path = keygen(args.key_path.expanduser(), args.public_module, force=args.force)
            print(f"Generated RSA-3072 private key outside repository: {key_path}")
            print(f"Embedded public key: {public_path}")
            print("Keep the private key backed up securely. Commit only the public trust module.")
            return 0
        if not args.package or not args.source or not args.version or (args.notes_file is None and args.notes is None):
            raise ValueError("Publishing requires --package, --source, --version, and Vietnamese --notes-file or --notes")
        result = publish(
            args.package.expanduser(),
            Path(args.source).expanduser(),
            args.version,
            args.min_version,
            args.channel,
            _load_notes(args),
            args.key_path.expanduser(),
        )
        print(json.dumps(result, ensure_ascii=False, sort_keys=True))
        return 0
    except Exception as exc:
        print(f"make-update.py: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
