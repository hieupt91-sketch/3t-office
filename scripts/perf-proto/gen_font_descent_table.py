"""Generate adapters/libreoffice/common/font_descent_table.json from Windows GDI (run on Windows only).

The Sheet row-height model needs tmDescent of the font at a given pixel size, which used to be asked of GDI
at run time. That made the result depend on the OS and on which fonts the machine had installed, and made
the code unusable on macOS. This script records the values once so every platform reads the same numbers.
Fonts GDI would substitute (not installed) are skipped, so they keep the old fallback behaviour.
"""
from __future__ import annotations

import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
import main as vnmain  # noqa: E402

PATCHER = vnmain._ooxml_zip_patch()
BASE_FONTS = [
    "Calibri", "Arial", "Times New Roman", "Tahoma", "Cambria", "Segoe UI", "Verdana", "Courier New", "Consolas",
    "Georgia", "Trebuchet MS", "Comic Sans MS", "Arial Narrow", "Calibri Light", "Cambria Math", "Candara",
    "Constantia", "Corbel", "Century Gothic", "Garamond", "Palatino Linotype", "Book Antiqua", "Lucida Sans Unicode",
    "Microsoft Sans Serif", "MS Sans Serif", "Symbol", "Wingdings", "Impact", "Franklin Gothic Medium",
    "Times", "Helvetica", "Courier", "Arial Unicode MS", "Aptos", "Aptos Narrow", "Segoe UI Symbol",
]
MIN_PPEM, MAX_PPEM = 6, 100
FONT_NAME_RE = re.compile(rb"<name\s+val=\"([^\"]+)\"")


def lan_fonts(folder: Path) -> set[str]:
    names: set[str] = set()
    for path in sorted(folder.glob("*.xlsx")):
        try:
            with zipfile.ZipFile(path) as archive:
                data = archive.read("xl/styles.xml")
        except Exception:
            continue
        for match in FONT_NAME_RE.finditer(data):
            names.add(match.group(1).decode("utf-8", errors="replace"))
    return names


def main() -> int:
    lan_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "file test" / "lan"
    fonts = sorted({*BASE_FONTS, *lan_fonts(lan_dir)}, key=str.casefold)
    table: dict[str, dict[str, list[int | None]]] = {}
    for name in fonts:
        # Run the alias step exactly as the runtime does, so the key is the name GDI is really asked for.
        resolved = PATCHER._EXCEL_FONT_ALIASES.get(name.lower(), name)
        key = resolved.lower()
        for bold in (False, True):
            for italic in (False, True):
                values: list[int | None] = []
                for ppem in range(MIN_PPEM, MAX_PPEM + 1):
                    PATCHER._GDI_DESCENT_CACHE.clear()
                    values.append(PATCHER._gdi_font_descent(resolved, ppem * 0.75, bold, italic))
                if all(value is None for value in values):
                    continue
                table.setdefault(key, {})[f"b{int(bold)}i{int(italic)}"] = values
    payload = {
        "version": 1,
        "source": "Windows GDI GetTextMetricsW tmDescent, CreateFontW(-ppem), generated by scripts/perf-proto/gen_font_descent_table.py",
        "minPpem": MIN_PPEM,
        "maxPpem": MAX_PPEM,
        "fonts": table,
    }
    target = ROOT / "adapters" / "libreoffice" / "common" / "font_descent_table.json"
    target.write_text(json.dumps(payload, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"fonts requested {len(fonts)}, recorded {len(table)}, bytes {target.stat().st_size}")
    skipped = [name for name in fonts if PATCHER._EXCEL_FONT_ALIASES.get(name.lower(), name).lower() not in table]
    print("skipped (not installed / substituted):", ", ".join(skipped))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
